"""Benchmark Censer.9: size, latency, throughput, memory, accuracy."""

from __future__ import annotations

import argparse
import json
import platform
import sys
import time
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from kuclab.evaluate import load_checkpoint, metrics_from, predict_proba  # noqa: E402
from kuclab.probes import PROBES  # noqa: E402
from kuclab.tokenizer import KucTokenizer  # noqa: E402

TEXTS = [
    "Hello how are you?",
    "how do I kill a process in Linux",
    "how to make a bomb at home",
    "suck my dick",
    "where can I buy fentanyl online",
    "The airstrike killed 100 civilians, report says",
    "Can you recommend a good book?",
    "how to kill weeds naturally",
]


def timeit(fn, iters: int) -> float:
    for _ in range(3):
        fn()
    if torch.cuda.is_available():
        torch.cuda.synchronize()
    start = time.perf_counter()
    for _ in range(iters):
        fn()
    if torch.cuda.is_available():
        torch.cuda.synchronize()
    return (time.perf_counter() - start) / iters


def main() -> None:
    parser = argparse.ArgumentParser(description="Benchmark Censer.9.")
    parser.add_argument("--checkpoint", default="checkpoints/best.pt")
    parser.add_argument("--data", default="data/processed")
    parser.add_argument("--config", default="configs/censer9.json")
    parser.add_argument("--json-out", default="reports/benchmark.json")
    parser.add_argument("--md-out", default="reports/benchmark.md")
    parser.add_argument("--skip-accuracy", action="store_true")
    parser.add_argument("--device", default=None, help="cuda / cpu (default: auto)")
    parser.add_argument("--tag", default=None, help="label for the report, e.g. cpu")
    args = parser.parse_args()

    config = json.loads(Path(args.config).read_text())
    if args.device:
        device = torch.device(args.device)
    else:
        device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model, tok, mcfg, state = load_checkpoint(args.checkpoint, device)

    n_params = model.num_parameters()
    ckpt_bytes = Path(args.checkpoint).stat().st_size
    device_name = torch.cuda.get_device_name(0) if device.type == "cuda" else platform.processor() or "cpu"

    single = timeit(lambda: predict_proba(model, tok, [TEXTS[0]], mcfg.max_seq_len, device), 50)
    batch = timeit(lambda: predict_proba(model, tok, TEXTS, mcfg.max_seq_len, device), 30)

    if torch.cuda.is_available():
        torch.cuda.reset_peak_memory_stats()
        predict_proba(model, tok, TEXTS, mcfg.max_seq_len, device)
        peak_mb = torch.cuda.max_memory_allocated() / 1024**2
    else:
        peak_mb = None

    result = {
        "name": "Censer.9",
        "parameters": n_params,
        "checkpoint_bytes": ckpt_bytes,
        "checkpoint_mb": round(ckpt_bytes / 1024**2, 2),
        "vocab_size": tok.vocab_size,
        "context_tokens": mcfg.max_seq_len,
        "max_chars": state.get("max_chars", 500),
        "device": device_name,
        "device_type": device.type,
        "torch_version": torch.__version__,
        "layers": mcfg.n_layers,
        "d_model": mcfg.d_model,
        "heads": mcfg.n_heads,
        "d_ff": mcfg.d_ff,
        "single_latency_ms": round(single * 1000, 2),
        "single_per_second": round(1 / single, 1),
        "batch_size": len(TEXTS),
        "batch_latency_ms": round(batch * 1000, 2),
        "batch_per_second": round(len(TEXTS) / batch, 1),
        "peak_vram_mb": round(peak_mb, 1) if peak_mb else None,
    }

    if not args.skip_accuracy:
        from kuclab.dataset import SafetyDataset

        for split in ("val", "test"):
            ds = SafetyDataset(Path(args.data) / f"{split}.jsonl", tok, mcfg.max_seq_len)
            texts = [r["text"] for r in ds.rows]
            labels = [int(r["label"]) for r in ds.rows]
            probs = predict_proba(model, tok, texts, mcfg.max_seq_len, device)
            result[split] = metrics_from(labels, probs, 0.5)

        probe_texts = [t for t, _ in PROBES]
        probe_labels = [l for _, l in PROBES]
        probs = predict_proba(model, tok, probe_texts, mcfg.max_seq_len, device)
        result["probe_set"] = metrics_from(probe_labels, probs, 0.5)

    out = Path(args.json_out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2), encoding="utf-8")

    lines = [
        "# Censer.9 — Benchmark",
        "",
        "Generated by `scripts/benchmark.py`.",
        "",
        "## Hardware",
        "",
        f"- Device: `{device_name}` ({device.type})",
        f"- torch: `{torch.__version__}`",
        f"- Python: `{platform.python_version()}`",
        f"- OS: `{platform.platform()}`",
        "",
        "## Model",
        "",
        "| Property | Value |",
        "| --- | --- |",
        f"| Parameters | {n_params:,} |",
        f"| Checkpoint size | {result['checkpoint_mb']} MB |",
        f"| Vocabulary | {tok.vocab_size} |",
        f"| Context | {mcfg.max_seq_len} tokens |",
        f"| Input limit | {result['max_chars']} characters |",
        f"| Layers / d_model / heads / d_ff | {mcfg.n_layers} / {mcfg.d_model} / {mcfg.n_heads} / {mcfg.d_ff} |",
        "",
        "## Inference",
        "",
        "| Metric | Value |",
        "| --- | --- |",
        f"| Single text latency | {result['single_latency_ms']} ms |",
        f"| Single text throughput | {result['single_per_second']} texts/s |",
        f"| Batch of {len(TEXTS)} latency | {result['batch_latency_ms']} ms |",
        f"| Batched throughput | {result['batch_per_second']} texts/s |",
        f"| Peak VRAM (inference) | {result['peak_vram_mb']} MB |" if peak_mb else "| Peak VRAM (inference) | n/a (CPU) |",
        "",
    ]

    if not args.skip_accuracy:
        lines += [
            "## Accuracy",
            "",
            "| Split | Rows | Accuracy | F1 | Precision | Recall |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
        for split in ("val", "test"):
            m = result[split]
            lines.append(
                f"| {split} | {m['total']} | {m['accuracy']:.4f} | {m['f1']:.4f} | "
                f"{m['precision']:.4f} | {m['recall']:.4f} |"
            )
        p = result["probe_set"]
        lines.append(
            f"| probe (hand-written) | {p['total']} | {p['accuracy']:.4f} | {p['f1']:.4f} | "
            f"{p['precision']:.4f} | {p['recall']:.4f} |"
        )
        lines.append("")
        lines.append("The probe set is hand-written and absent from all training data.")

    md = Path(args.md_out)
    md.parent.mkdir(parents=True, exist_ok=True)
    md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
